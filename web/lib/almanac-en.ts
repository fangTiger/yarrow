const ENGLISH_MONTHS = [
  "January", "February", "March", "April", "May", "June",
  "July", "August", "September", "October", "November", "December",
] as const;

export function translateGanzhi(value: string): string | undefined {
  const [stem, branch, ...rest] = [...value];
  if (rest.length || !stem || !branch) return undefined;
  const stemEn = STEM_EN[stem];
  const branchEn = BRANCH_EN[branch];
  return stemEn && branchEn ? `${stemEn} ${branchEn}` : undefined;
}

export function translateLunarDate(value: string): string | undefined {
  const match = /^([〇零一二三四五六七八九]+)年(闰?)([^月]+)月(.+)$/u.exec(value);
  if (!match) return undefined;
  const [, yearText, leap, monthText, dayText] = match;
  if (!yearText || !monthText || !dayText) return undefined;
  const year = [...yearText].map((digit) => CHINESE_DIGIT[digit]).join("");
  const month = LUNAR_MONTH_EN[monthText];
  const day = LUNAR_DAY_NUMBER[dayText];
  if (!year || !month || !day) return undefined;
  return `${leap ? "Leap " : ""}${month} lunar month · day ${day} · ${year}`;
}

export function formatEnglishSolarDate(value: string): string | undefined {
  const match = /^(\d{4})-(\d{2})-(\d{2})/u.exec(value);
  if (!match) return undefined;
  const [, year, monthText, dayText] = match;
  const month = ENGLISH_MONTHS[Number(monthText) - 1];
  const day = Number(dayText);
  return year && month && day ? `${month} ${day}, ${year}` : undefined;
}

export function translateClash(
  description: string,
  direction: string,
): string | undefined {
  const match = /^\(([^)]+)\)(.)$/u.exec(description);
  if (!match) return undefined;
  const cycle = match[1] ? translateGanzhi(match[1]) : undefined;
  const zodiac = match[2] ? ZODIAC_EN[match[2]] : undefined;
  const directionEn = DIRECTION_EN[direction];
  return cycle && zodiac && directionEn ? `${zodiac} (${cycle}) · ${directionEn}` : undefined;
}
